param()

$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$demoRoot = Join-Path $projectRoot ('.conductor/demos/' + [guid]::NewGuid().ToString())
$fixtureRoot = Join-Path $demoRoot 'fixture-repo'
$statePath = Join-Path $demoRoot 'state'
$binaryPath = Join-Path $projectRoot 'target/debug/dev-conductor.exe'

Push-Location -LiteralPath $projectRoot
try {
    & cargo build --locked
    if ($LASTEXITCODE -ne 0) { throw 'Build failed' }
    New-Item -ItemType Directory -Path $fixtureRoot -Force | Out-Null
    $resolvedFixture = (Resolve-Path -LiteralPath $fixtureRoot).Path
    $resolvedDemo = (Resolve-Path -LiteralPath $demoRoot).Path
    if (-not $resolvedFixture.StartsWith($resolvedDemo + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
        throw 'Fixture is outside this demo directory'
    }

    function Invoke-FixtureGit {
        param([string[]]$CommandArgs)
        & git -C $resolvedFixture @CommandArgs | Out-Null
        if ($LASTEXITCODE -ne 0) { throw 'Fixture Git operation failed' }
    }

    function Invoke-Conductor {
        param([string[]]$CommandArgs)
        $json = & $binaryPath --state $statePath @CommandArgs
        if ($LASTEXITCODE -ne 0) { throw 'Conductor operation failed; inspect recorded task state' }
        $json | ConvertFrom-Json
    }

    Invoke-FixtureGit @('init', '-b', 'main')
    Invoke-FixtureGit @('config', 'core.autocrlf', 'false')
    [IO.File]::WriteAllText((Join-Path $fixtureRoot 'README.md'), "# Demo fixture`nThis repository is expendable and belongs only to this demo.`n", [Text.UTF8Encoding]::new($false))
    [IO.File]::WriteAllText((Join-Path $fixtureRoot 'AGENTS.md'), "Create only the approved result file. Review evidence separately from execution.`n", [Text.UTF8Encoding]::new($false))
    Invoke-FixtureGit @('add', '.')
    Invoke-FixtureGit @('-c', 'user.name=Demo Fixture', '-c', 'user.email=fixture@example.invalid', '-c', 'core.hooksPath=', '-c', 'commit.gpgsign=false', 'commit', '-m', 'Disposable demo fixture')

    $registration = Invoke-Conductor @('register', $fixtureRoot)
    $prepared = Invoke-Conductor @('create', $registration.id, 'Create a supervised fixture result', '--acceptance', 'Inspect a new root file and its host byte-comparison receipt', '--contents', "# Fixture result`nGenerated by the deterministic fake backend.`n")
    $approved = Invoke-Conductor @('approve', $prepared.task.id, '--revision', [string]$prepared.task.revision, '--digest', $prepared.assignment_digest, '--by', 'Demo fixture approval (simulated)')
    $result = Invoke-Conductor @('run', $approved.task.id, '--revision', [string]$approved.task.revision)
    $resultPath = Join-Path $demoRoot 'demo-result.json'
    $result | Add-Member -NotePropertyName state_path -NotePropertyValue $statePath
    [IO.File]::WriteAllText($resultPath, ($result | ConvertTo-Json -Depth 30), [Text.UTF8Encoding]::new($false))
    $attempt = $result.task.attempts[-1]
    [pscustomobject]@{
        task_id = $result.task.id
        status = $result.task.status
        revision = $result.task.revision
        workspace = $attempt.workspace
        patch = $attempt.diff.path
        host_check = $attempt.receipt.check
        verification = $attempt.receipt.result
        execution_pid = $attempt.process_receipt.identity.pid
        execution_exit_code = $attempt.process_receipt.exit_code
        execution_log = $attempt.process_receipt.stdout.artifact.path
        verifier_pid = $attempt.receipt.process_receipt.identity.pid
        verifier_exit_code = $attempt.receipt.exit_code
        owned_trees_terminated = ($attempt.process_receipt.tree_terminated -and $attempt.receipt.process_receipt.tree_terminated)
        human_review = 'pending'
        state_path = $statePath
        result_json = $resultPath
    } | ConvertTo-Json
    Get-Content -LiteralPath $attempt.diff.path
} finally {
    Pop-Location
}
